export function phrase(
  locale: Locale,
  hebrew: string,
  vars?: Record<string, string | number>,
): string {
  const row = PHRASES[hebrew]
  let text = !row || locale === 'he' ? hebrew : row[locale]
  if (vars) {
    for (const [key, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${key}}`, String(value))
    }
  }
  return text
}

export function hasPhrase(hebrew: string): boolean {
  return hebrew in PHRASES
}

/** Translate a JSX text chunk. Keeps the original when the trimmed text is unknown. */
export function phraseChunk(locale: Locale, value: string): string {
  const trimmed = value.trim()
  if (!trimmed) return value
  const next = phrase(locale, trimmed)
  if (next === trimmed) return value
  return next
}
